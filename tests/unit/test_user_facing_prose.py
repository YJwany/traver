"""Server-written prose that reaches the user has to be prose.

This project's recurring defect is a value that no other part of the program can read: an
aspect name that is not a ``TravelMode``, a ``packed`` pace the API rejects, a capability that
is declared but unreachable. There is a cheaper, more visible version of the same defect, and
it showed up in the exported itinerary:

    5 leg(s) use distance-based travel estimates, not measured routes

The server writes Chinese everywhere else — warnings, capability gaps, freshness findings — so
this English sentence appeared in the middle of an otherwise Chinese document that a traveller
prints and carries. Each individual piece was correct; only the language was wrong, and nothing
checked.

A test per string would rot, because the assertion and the string are copies of each other.
So this checks the property instead: **user-facing text generated by the server must not
contain a bare English identifier.** It is deliberately narrow — it looks only at strings the
server itself composes for a reader, and it allows the identifiers that are genuinely proper
nouns or format tokens, because a blanket "no ASCII" rule would flag ``UTC``, ``ISO``, a URL,
or a provider name, and a test that must be relaxed constantly stops being read.
"""

from __future__ import annotations

import re
from datetime import date

from travel_api.domain.models import (
    ITEM_TYPE_LABELS,
    PACE_LABELS,
    TRAVEL_MODE_LABELS,
    Attraction,
    Coordinates,
    Itinerary,
    ItineraryItemType,
    Location,
    Pace,
    TravelMode,
    TripProfile,
)
from travel_api.services.aggregation import _disclose_unserved_travel_mode
from travel_api.services.route_optimizer import RouteOptimizer

#: Two or more consecutive ASCII letters. A single trailing letter is not a word; ``12km``
#: would match ``km`` and is not what this is about, so the pattern requires a word boundary
#: and at least two letters.
_WORD = re.compile(r"[A-Za-z]{2,}")

#: Words that may legitimately appear in server prose. Anything not here and not part of a
#: longer allowed token is reported. Kept short on purpose: every entry is a decision that a
#: reader is expected to understand this word, and an unexplained one is the bug.
ALLOWED = {
    # Proper nouns and product names. A traveller reading Chinese still recognises these, and
    # translating 高德 to "Amap" or OSRM to a Chinese phrase would make the prose less clear.
    "OpenStreetMap",
    "OSRM",
    "Amap",
    "Open",
    "Meteo",
    # 高德's own console calls the tier 「Web服务」, so this word is what the user will be
    # looking for on the page. Translating or dropping it would make the advice harder to act
    # on, which is the opposite of what this check is for.
    "Web",
    # Units and formats that are conventional in Chinese technical prose.
    "UTC",
    "ISO",
    "ID",
    "URL",
    "JSON",
    "Key",
    "API",
    # Provider identifiers are machine names; the reader sees the display name beside them.
    "openstreetmap",
    "amap",
    "osrm",
    "fixture",
    "mock",
    "wikipedia",
}


def _english_words(text: str) -> set[str]:
    return {word for word in _WORD.findall(text) if word not in ALLOWED}


def _profile() -> TripProfile:
    return TripProfile(
        destination="杭州",
        start_date=date(2026, 10, 3),
        end_date=date(2026, 10, 5),
        pace=Pace.BALANCED,
    )


def test_the_travel_mode_disclosure_is_written_in_chinese():
    """The disclosure a traveller reads when their mode was not served."""
    for mode in (None, *TravelMode):
        profile = (
            _profile() if mode is None else _profile().model_copy(update={"travel_mode": mode})
        )
        itinerary = Itinerary(days=[], conflicts=[])
        _disclose_unserved_travel_mode(itinerary, profile, [], ())
        for conflict in itinerary.conflicts:
            assert not _english_words(conflict), (
                f"the disclosure for mode={mode!r} contains bare English: {conflict!r}"
            )


def test_an_estimated_leg_is_disclosed_in_chinese():
    """The other direction: with no routes at all, the estimate disclosure is what is left."""
    profile = _profile()

    def _place(name: str, latitude: float, longitude: float) -> Attraction:
        return Attraction(
            canonical_name=name,
            location=Location(
                address=f"{name}路 1 号",
                city="杭州",
                coordinates=Coordinates(latitude=latitude, longitude=longitude),
            ),
        )

    attractions = [_place("西湖", 30.25, 120.15), _place("灵隐寺", 30.24, 120.10)]
    itinerary = RouteOptimizer().optimize(
        profile=profile,
        hotel_id=None,
        hotel_coordinates=(30.25, 120.15),
        attractions=attractions,
        restaurants=[],
        routes=[],
    )
    # The itinerary must actually have produced the disclosure, or the assertion below is
    # vacuous on a plan that simply had nothing to say.
    assert itinerary.conflicts, "no conflicts at all: the fixture no longer produces the case"
    for conflict in itinerary.conflicts:
        assert not _english_words(conflict), f"itinerary conflict contains English: {conflict!r}"


def test_every_item_kind_and_pace_has_a_chinese_label():
    """The tables the export prints from, checked against the enums they describe.

    ``ITEM_TYPE_LABELS``/``PACE_LABELS``/``TRAVEL_MODE_LABELS`` are what stop a raw identifier
    reaching a document. A new enum member with no label would fall back to the identifier,
    which is exactly the leak this file exists to catch — so the check is exhaustiveness, not
    a sample.
    """
    for member in ItineraryItemType:
        assert member.value in ITEM_TYPE_LABELS, f"{member.value} has no label"
        assert not _english_words(ITEM_TYPE_LABELS[member.value])
    for member in Pace:
        assert member.value in PACE_LABELS, f"{member.value} has no label"
        assert not _english_words(PACE_LABELS[member.value])
    for member in TravelMode:
        assert member.value in TRAVEL_MODE_LABELS, f"{member.value} has no label"
        assert not _english_words(TRAVEL_MODE_LABELS[member.value])
